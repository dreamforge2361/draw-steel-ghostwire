// 0.3.131 wave smoke — native canvas hit VFX, with AA / Sequencer / JB2A all switched off.
//
// The thing this wave fixed is a *blank canvas*, and a blank canvas is exactly what a Node smoke
// cannot see. So the assertions here are about the three things that made it blank, each of which
// is checkable without a browser:
//
//   A. the classifier still routes Double Tap and the rest of the ammo allowlist to `gun`;
//   B. every asset a profile can reach lives under `modules/draw-steel-ghostwire/assets/`, never
//      under `modules/jb2a_*` or `modules/autoanimations` — the optional Sequencer keys are the one
//      allowed exception and they are never on a required path;
//   C. no v7-only PIXI Graphics call survives outside the version shim, targets resolve from more
//      than the two sources that were both empty on an ability card, the beat is relayed to the
//      table, and the 0.3.130 teardown is still wired to all three hooks.
//
// Run: `node tools/wave-03131-smoke.mjs`

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  HIT_FX_KINDS, HIT_FX_PROFILES, SPELL_FLAVOURS,
  classifyHit, hitFxProfile, spellFlavour,
} from "../scripts/hit-fx.mjs";
import { FX_TEXTURES, FX_ASSET_DIR, fxAssetPath } from "../scripts/fx-canvas.mjs";
import { AMMO_ABILITY_COSTS, ammoCostForDsid } from "../scripts/ammo.mjs";

const MODULE_ID = "draw-steel-ghostwire";
const fail = [];
const note = (pass, msg) => { if (pass) console.log(`  ✓ ${msg}`); else { fail.push(msg); console.log(`  ✗ ${msg}`); } };

const read = p => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const readJson = p => JSON.parse(read(p));
/** Source with every comment line dropped — a header that *names* a thing is not the thing. */
const code = text => text.split("\n").filter(line => !/^\s*(\/\/|\*|\/\*)/.test(line)).join("\n");
const sha = p => createHash("sha256").update(readFileSync(p)).digest("hex");

const hitFx = read("scripts/hit-fx.mjs");
const hitFxCode = code(hitFx);
const fxCanvas = read("scripts/fx-canvas.mjs");
const fxCanvasCode = code(fxCanvas);
const manifest = readJson("module.json");

console.log("0.3.131 wave smoke\n");

/* ------------------------------------------------------------------ A: the classifier still routes a gun */

console.log("A) Classification — Double Tap is a gun, and so is the rest of the allowlist");

note(ammoCostForDsid("double-tap") > 0, "double-tap is on the ammo allowlist (the prime smoke's route to `gun`)");
note(classifyHit({ gunAbility: ammoCostForDsid("double-tap") > 0, keywords: ["ranged", "strike", "weapon"] }) === "gun",
  "and it classifies as `gun`, with no gear stamp behind it");
for (const dsid of ["controlled-pair", "suppressing-fire", "breach-and-clear"]) {
  note(classifyHit({ gunAbility: ammoCostForDsid(dsid) > 0 }) === "gun", `${dsid} classifies as \`gun\``);
}
{
  const misrouted = Object.keys(AMMO_ABILITY_COSTS)
    .filter(dsid => classifyHit({ gunAbility: ammoCostForDsid(dsid) > 0 }) !== "gun");
  note(!misrouted.length, `all ${Object.keys(AMMO_ABILITY_COSTS).length} ammo abilities route to \`gun\`${misrouted.length ? ` — missed ${misrouted.join(", ")}` : ""}`);
}
note(classifyHit({ range: "Medium", ammoFamily: "handgun" }) === "gun", "a weapon that eats rounds is still a gun");
note(classifyHit({ range: "Short", keywords: ["ranged", "strike", "weapon"] }) === null, "and a bow is still nobody's business");

/* ------------------------------------------------------------------ B: the assets are Ghostwire's own */

console.log("\nB) Assets — in this module, generated by this repository");

note(existsSync("assets/fx"), "assets/fx/ exists");
note(FX_ASSET_DIR === `modules/${MODULE_ID}/assets/fx`, `and profiles reach it at ${FX_ASSET_DIR}`);
for (const name of FX_TEXTURES) {
  const path = fxAssetPath(name).replace(`modules/${MODULE_ID}/`, "");
  const ok = existsSync(path);
  note(ok, `${name}: ${path} ships in the module`);
  if (!ok) continue;
  const head = readFileSync(path).subarray(0, 8);
  note(head.equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])), `${name}: and it is a real PNG`);
}
{
  // Nothing in the folder may be art nobody can point at a generator for.
  const strays = readdirSync("assets/fx")
    .filter(f => f !== "README.md" && !FX_TEXTURES.includes(f.replace(/\.png$/, "")));
  note(!strays.length, `nothing unaccounted for in assets/fx${strays.length ? ` — ${strays.join(", ")}` : ""}`);
}
{
  const before = FX_TEXTURES.map(name => sha(fxAssetPath(name).replace(`modules/${MODULE_ID}/`, "")));
  execFileSync(process.execPath, ["tools/make-fx-assets.mjs"], { stdio: "ignore" });
  const after = FX_TEXTURES.map(name => sha(fxAssetPath(name).replace(`modules/${MODULE_ID}/`, "")));
  note(before.every((hash, i) => hash === after[i]),
    "re-running tools/make-fx-assets.mjs is a byte-for-byte no-op — the committed PNGs are reproducible");
}
{
  const provenance = read("assets/fx/README.md");
  note(/tools\/make-fx-assets\.mjs/.test(provenance), "assets/fx/README.md names the generator");
  note(/CC BY-NC-SA/.test(provenance) && /No third-party art is vendored/i.test(provenance),
    "and says plainly that no JB2A art was vendored, and why");
}

console.log("\nB2) No required path points outside this module");

for (const kind of HIT_FX_KINDS) {
  const profile = hitFxProfile(kind, "");
  const path = profile.sound.replace(`modules/${MODULE_ID}/`, "");
  note(existsSync(path), `${kind}: its sound ships in the module (${path.split("/").pop()})`);
  note(profile.sound.startsWith(`modules/${MODULE_ID}/assets/`), `${kind}: and resolves under this module's assets/`);
}
for (const flavour of SPELL_FLAVOURS) {
  note(flavour.sound.startsWith(`modules/${MODULE_ID}/assets/`), `spell/${flavour.key}: sound is a module asset`);
}
{
  // The Sequencer keys are database names, not paths, and they are the one optional route. What
  // must never appear is a *file path* into somebody else's module folder.
  const badPath = /modules\/(jb2a[^"'`\s]*|JB2A[^"'`\s]*|autoanimations|sequencer)\//;
  for (const [label, source] of [["hit-fx.mjs", hitFxCode], ["fx-canvas.mjs", fxCanvasCode]]) {
    note(!badPath.test(source), `${label}: no runtime path into modules/jb2a_* / modules/autoanimations`);
  }
  note(!/autoanimations/i.test(hitFxCode) && !/autoanimations/i.test(fxCanvasCode),
    "and no code path asks for Automated Animations at all");
}
note(!manifest.relationships?.requires?.length,
  "module.json declares no required relationships");
for (const id of ["sequencer", "autoanimations", "JB2A_DnD5e", "ds-aa-bridge"]) {
  const named = JSON.stringify(manifest.relationships ?? {}).includes(id);
  note(!named, `module.json's relationships never name ${id}`);
}
note(manifest.relationships?.systems?.some(rel => rel.id === "draw-steel"),
  "while the draw-steel system relationship is untouched");
note(/game\.modules\.get\("sequencer"\)\?\.active/.test(hitFxCode), "Sequencer is probed, never assumed");

/* ------------------------------------------------------------------ C: why it was blank */

console.log("\nC1) PIXI 8 safety — no v7-only Graphics call outside the shim");

{
  const legacy = /\b(lineStyle|beginFill|endFill|drawCircle|drawRect|quadraticCurveTo)\s*\(/g;
  const inHitFx = hitFxCode.match(legacy) ?? [];
  note(!inHitFx.length, `hit-fx.mjs makes no raw Graphics call${inHitFx.length ? ` — found ${[...new Set(inHitFx)].join(", ")}` : ""}`);
  note(/from "\.\/fx-canvas\.mjs"/.test(hitFxCode), "it draws through scripts/fx-canvas.mjs instead");
}
{
  const helpers = ["strokePath", "fillCircle", "strokeCircle", "strokeArc", "strokeQuad"];
  for (const helper of helpers) {
    const body = fxCanvas.split(`export function ${helper}(`)[1]?.split("\nexport ")[0] ?? "";
    note(/isLegacyGraphics\(graphics\)/.test(body), `${helper} branches on isLegacyGraphics (PIXI 7) ...`);
    note(/\.stroke\(\{|\.fill\(\{/.test(body), `... and has a PIXI 8 fill()/stroke() path`);
  }
  note(/typeof graphics\?\.lineStyle === "function"/.test(fxCanvasCode),
    "and the version test reads the instance, not a version string");
  note(/PIXI\?\.BLEND_MODES\?\.ADD \?\? "add"/.test(fxCanvasCode),
    "additive blending resolves on both engines");
}

console.log("\nC2) Targets — more than the two sources that were both empty");

{
  const block = hitFx.split("function targetPoints(")[1]?.split("\nfunction ")[0] ?? "";
  note(/system\.targetTokens/.test(block), "targetPoints still tries system.targetTokens ...");
  note(/system\.targets/.test(block), "... then the raw target UUIDs ...");
  note(/resultParts\(message\)/.test(block), "... then the roll part's own targets ...");
  note(/game\.users\?\.get\?\.\(userId\)/.test(block), "... then the rolling user's target set ...");
  note(/game\.user\?\.targets/.test(block), "... and only last this client's own targets");
  note(/function tokenPoint\(/.test(hitFxCode) && /getActiveTokens/.test(hitFxCode),
    "and a speaker with no token id falls back to the actor's token on the scene");
  note(/via: "origin"/.test(hitFxCode) && /style: "muzzle"/.test(hitFxCode),
    "with nothing downrange, the shooter's own token still flashes rather than drawing nothing");
}

console.log("\nC3) The whole table draws, not only the roller");

note(/game\?\.socket\?\.emit\(SOCKET/.test(hitFxCode), "the resolved points go out on the module socket");
note(/game\.socket\.on\(SOCKET, onHitFxSocket\)/.test(hitFxCode), "and every client listens for them");
note(/silent: true/.test(hitFxCode), "receivers draw without replaying the sound (AudioHelper already broadcast it)");
note(/mode: "builtin"/.test(hitFxCode), "receivers draw the built-in beat, never a second Sequencer effect");
note(/relay: false/.test(hitFxCode), "and never relay a relay");
note(/hitFxBroadcast/.test(hitFxCode), "there is a world setting to turn the relay off");
{
  const lang = readJson("lang/en.json").GHOSTWIRE.HitFx.Settings;
  for (const key of ["Enabled", "Volume", "Sequencer", "Broadcast"]) {
    note(typeof lang[key]?.Name === "string" && typeof lang[key]?.Hint === "string",
      `the ${key} setting has a name and a hint`);
  }
}

console.log("\nC4) Sprites are visible, and the vector floor is still there");

for (const kind of HIT_FX_KINDS) {
  const profile = HIT_FX_PROFILES[kind];
  note(Number.isFinite(profile.impactSize) && (profile.impactSize >= 1),
    `${kind}: the impact is at least a full grid square across (${profile.impactSize})`);
  note(Number.isFinite(profile.core), `${kind}: it has a hot inner tint as well as an outer colour`);
}
note(HIT_FX_PROFILES.grenade.impactSize > HIT_FX_PROFILES.gun.impactSize,
  "a grenade still reads bigger than a bullet");
note(/const IMPACT_MS = (5[6-9]\d|[6-9]\d\d)/.test(hitFxCode), "and the impact holds longer than 0.3.130's 420 ms");
note(/createRig\(/.test(hitFxCode) && /spriteTravel\(/.test(hitFxCode) && /spriteImpact\(/.test(hitFxCode),
  "the primary path builds a sprite rig once and only transforms it");
note(/drawTravel\(/.test(hitFxCode) && /drawImpact\(/.test(hitFxCode),
  "and the vector beats survive as the floor when the textures are not cached yet");
note(/fxTexturesReady\(\)/.test(hitFxCode), "which is exactly the condition it checks");
note(/impact: false/.test(hitFxCode),
  "the half-and-half Sequencer case still draws travel only, so JB2A's impact is not doubled");

console.log("\nD) 0.3.130 teardown, kept and widened");

note(/const liveFrames = new Set\(\)/.test(hitFxCode), "live effects are still tracked in a Set");
for (const hook of ["canvasTearDown", "canvasReady", "deleteCombat"]) {
  note(new RegExp(`Hooks\\.on\\("${hook}"`).test(hitFxCode), `teardown is still wired to ${hook}`);
}
note(/teardownAllFrames\(\);/.test(hitFxCode), "and teardownAllFrames still runs on all three");
note(/destroyDisplay\(entry\.display\)/.test(hitFxCode),
  "each entry is destroyed children-first, so the new sprites go with the container");
note(/display\.destroy\(\{ children: true \}\)/.test(fxCanvasCode), "which is what destroyDisplay does");
note(/liveFrames\.delete\(entry\)/.test(hitFxCode), "and a finished effect leaves the set");
note(/preloadFxTextures\(\)/.test(hitFxCode),
  "the texture cache is re-warmed on canvasReady, after the teardown that emptied it");

/* ------------------------------------------------------------------ E: ship hygiene */

console.log("\nE) Version and docs");

note(manifest.version === "0.3.131", `module.json is ${manifest.version}`);
note(/`0\.3\.131`/.test(read("README.md")), "README has a 0.3.131 entry");
note(existsSync("docs/directors/03131-smoke.md"), "the Foundry checklist is written");
note(/Double Tap/.test(existsSync("docs/directors/03131-smoke.md") ? read("docs/directors/03131-smoke.md") : ""),
  "and its prime item is Double Tap");
note(/registerHitFx\(\);/.test(read("scripts/module.mjs")), "module.mjs still registers the hit FX");
note(/playHitFx\("grenade"/.test(read("scripts/grenades.mjs")), "and the grenade resolve still calls it directly");

/* ------------------------------------------------------------------ */

console.log(fail.length ? `\n0.3.131 smoke FAIL — ${fail.length}` : "\n0.3.131 smoke OK");
for (const msg of fail) console.log(`  - ${msg}`);
process.exit(fail.length ? 1 : 0);
