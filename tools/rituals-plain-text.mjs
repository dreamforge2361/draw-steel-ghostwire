#!/usr/bin/env node
/**
 * 0.3.134 (A) — put the plain-language block on every Ritual Working card.
 *
 * Michael's note: **Ward the Room** was pure jargon. The card told a player what a Veil barrier does
 * to "Magic-keyword / Veil remote targeting" and never once said, in words a new player could read,
 * what the thing looks like, what a **bane** buys them, or what **Magnitude**, **Scope**, **Seal**
 * and **Expires** mean *for that card*. Every one of the 47 Workings had the same hole.
 *
 * The text lives in `tools/data/ritual-plain-text.json`, keyed by card title, and this tool writes it
 * into `docs/raw/22-the-veil.md` directly after the card's **Formula Item form:** line. docs/raw stays
 * the single source of truth: `tools/raw-to-journals.mjs` builds the rulebook journal from it and
 * `tools/ritual-formulas-to-items.mjs` builds the Formula Item descriptions from it, so both get the
 * new text for free and a regenerate keeps it.
 *
 * Idempotent: the block is fenced by an HTML comment pair, and a re-run replaces whatever is between
 * the fences rather than adding a second copy. Missing or extra card entries are a hard error — a new
 * Working has to be written for a player before it ships.
 *
 * Run: node tools/rituals-plain-text.mjs
 *      then node tools/raw-to-journals.mjs and node tools/ritual-formulas-to-items.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const RAW = "docs/raw/22-the-veil.md";
const DATA = "tools/data/ritual-plain-text.json";
// The runtime copy. scripts/ritual-seal.mjs fetches this so a *sealed* Working card can print the
// same six lines the Formula Item does, instead of only the family's one-line generic scope.
const RUNTIME = "scripts/data/ritual-plain-text.json";
const OPEN = "<!-- plain-text:start -->";
const CLOSE = "<!-- plain-text:end -->";

const { cards } = JSON.parse(readFileSync(DATA, "utf8"));
const md = readFileSync(RAW, "utf8").replace(/\r\n/g, "\n");

/** The six fields, rendered. Bold labels match the rest of the card's vocabulary. */
function block(card) {
  return [
    OPEN,
    "",
    `**The story:** ${card.story}`,
    "",
    `**In plain words:** ${card.plain}`,
    "",
    "**What this card's words mean here:**",
    "",
    `- **Magnitude** — ${card.magnitude}`,
    `- **Scope** — ${card.scope}`,
    `- **Seal** — ${card.seal}`,
    `- **Expires** — ${card.expires}`,
    "",
    CLOSE,
  ].join("\n");
}

const seen = new Set();
const missing = [];
let out = md;

// Split on the card sections exactly as tools/ritual-formulas-to-items.mjs does, so the two tools can
// never disagree about what counts as a card.
const sections = md.split(/^(?=## )/m);
const rebuilt = sections.map(section => {
  if (!section.startsWith("## Ritual Workings — ") || section.startsWith("## Ritual Workings — Card Index")) return section;
  const chunks = section.split(/^(?=### )/m);
  return chunks.map((chunk, index) => {
    if (index === 0) return chunk;
    const title = chunk.split("\n")[0].replace(/^### /, "").replace(/\s*\*\(optional\)\*\s*$/, "").trim();
    const card = cards[title];
    if (!card) { missing.push(title); return chunk; }
    seen.add(title);

    // Strip any block a previous run wrote (fences included), then insert a fresh one.
    let body = chunk.replace(new RegExp(`\\n${OPEN}[\\s\\S]*?${CLOSE}\\n`, "g"), "\n");
    const formLine = /^\*\*Formula Item form:\*\*.*$/m.exec(body);
    if (!formLine) throw new Error(`${title}: no "Formula Item form:" line to anchor the plain-text block to`);
    const at = formLine.index + formLine[0].length;
    return `${body.slice(0, at)}\n\n${block(card)}${body.slice(at)}`;
  }).join("");
}).join("");

out = rebuilt;

const unused = Object.keys(cards).filter(title => !seen.has(title));
if (missing.length || unused.length) {
  for (const title of missing) console.error(`  no plain text written for card: ${title}`);
  for (const title of unused) console.error(`  plain text for a card that no longer exists: ${title}`);
  process.exit(1);
}

writeFileSync(RAW, out);
writeFileSync(RUNTIME, `${JSON.stringify({
  _comment: "GENERATED by tools/rituals-plain-text.mjs from tools/data/ritual-plain-text.json. Read at runtime by scripts/ritual-seal.mjs so a sealed Working card carries the same plain-language block as its Formula Item. Do not edit by hand.",
  cards,
}, null, 2)}
`);
console.log(`ritual plain text: ${seen.size} card(s) written into ${RAW} and ${RUNTIME}`);
