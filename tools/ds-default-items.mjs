#!/usr/bin/env node
/**
 * 0.3.127 (C) — snapshot Draw Steel's hero `defaultItems` that Ghostwire keeps, for the pregens.
 *
 * Why a committed snapshot rather than a live read:
 *
 *   The New-Hero path never needed one. `ds.CONFIG.hero.defaultItems` is a live Set of compendium
 *   UUIDs, scripts/module.mjs swaps five of them for Ghostwire's own at `init`, and Foundry copies
 *   whatever is left onto the sheet when the Actor is created. The pregens are built by a Node
 *   script with no Foundry and no `ds` global, so they were simply never given any — which is why
 *   **Catch Breath was missing from nine dossier sheets**.
 *
 *   The generator could read the system's LevelDB directly, but then `node tools/pregens-to-actors.mjs`
 *   would only reproduce the committed actors on a machine with the Draw Steel system installed at
 *   the right version, and `tools/pregen-regen-smoke.mjs` byte-compares that round trip on every run.
 *   So the read happens *here*, once, deliberately, and the result is committed.
 *
 * What is snapshotted: the stock Draw Steel defaults Ghostwire does **not** replace. The five it
 * does replace (Ride, Charge, Defend, Heal, Aid Attack) are Ghostwire Items already living in
 * src/packs/abilities/, and the generator reads those from disk. The two generic Free Strikes are
 * deliberately absent (B44c), and so are the Matrix Verbs (B117).
 *
 * Run with Foundry closed, after a Draw Steel system upgrade:
 *   node tools/ds-default-items.mjs
 * then regenerate the pregens and rebuild the pack:
 *   node tools/pregens-to-actors.mjs && node tools/build-packs.mjs pregens
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { foundryRequire } from "./lib/foundry-require.mjs";

const { ClassicLevel } = foundryRequire("classic-level");

const OUT = "docs/masters/pregens/default-items.json";
const DATA_ROOT = process.env.FOUNDRY_DATA ?? "C:/Users/mfran/Dropbox/FoundryVTT/Data";
const PACK = join(DATA_ROOT, "systems/draw-steel/packs/abilities");

/**
 * The stock defaults Ghostwire keeps, in the order they should land on a sheet.
 *
 * Drawn from `ds.CONFIG.hero.defaultItems` minus `DEFAULT_ITEM_SWAPS` (scripts/module.mjs), minus
 * the two Free Strikes scripts/free-strikes.mjs strips. Keyed by `_dsid` so a system upgrade that
 * re-ids an ability still resolves.
 */
export const KEPT_DEFAULT_DSIDS = [
  "catch-breath",
  "escape-grab",
  "grab",
  "knockback",
  "stand-up",
  "advance",
  "disengage",
];

/** Never snapshot these, whatever the system ships them as. */
const FORBIDDEN = new Set(["melee-free-strike", "ranged-free-strike"]);

if (!existsSync(PACK)) {
  console.error(`No Draw Steel abilities pack at ${PACK}. Set FOUNDRY_DATA to your Foundry data folder.`);
  process.exit(1);
}

const db = new ClassicLevel(PACK, { valueEncoding: "json" });
const byDsid = new Map();
let systemVersion = null;
for await (const [key, value] of db.iterator()) {
  if (!key.startsWith("!items!")) continue;
  const dsid = value?.system?._dsid;
  if (!dsid || !KEPT_DEFAULT_DSIDS.includes(dsid)) continue;
  systemVersion ??= value?._stats?.systemVersion ?? null;
  byDsid.set(dsid, value);
}
await db.close();

const missing = KEPT_DEFAULT_DSIDS.filter(dsid => !byDsid.has(dsid));
if (missing.length) {
  console.error(`Draw Steel's abilities pack has no ${missing.join(", ")} — refusing to write a partial snapshot.`);
  process.exit(1);
}

/**
 * Compendium furniture goes: `_key` and `folder` belong to the system's own pack, `_stats` records
 * when *they* built it, and `ownership` is re-stamped by the generator's `embed()`. What is left is
 * the ability itself, byte for byte.
 */
const clean = doc => {
  const { _key, _stats, folder, ownership, ...rest } = doc;
  if (FORBIDDEN.has(rest.system?._dsid)) throw new Error(`refusing to snapshot ${rest.system._dsid}`);
  return { ...rest, folder: null, sort: 0 };
};

const snapshot = {
  _note: "Generated by tools/ds-default-items.mjs — do not hand-edit. Stock Draw Steel hero default "
    + "abilities that Ghostwire keeps, embedded on every pregen by tools/pregens-to-actors.mjs. The "
    + "five Ghostwire swaps (Drive / Rush / Take Cover / Patch Up / Spot Target) are NOT here: they "
    + "are module Items under src/packs/abilities/. Free Strikes (B44c) and Matrix Verbs (B117) are "
    + "deliberately excluded.",
  source: { system: "draw-steel", pack: "abilities", systemVersion },
  dsids: [...KEPT_DEFAULT_DSIDS],
  items: KEPT_DEFAULT_DSIDS.map(dsid => clean(byDsid.get(dsid))),
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + "\n");
console.log(`${OUT}: ${snapshot.items.length} stock defaults from draw-steel ${systemVersion ?? "?"}`);
for (const item of snapshot.items) console.log(`  ${item.system._dsid.padEnd(14)} ${item._id}  ${item.name}`);
